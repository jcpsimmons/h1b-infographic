#!/usr/bin/env node
// Writes src/charts/registry.ts from every src/charts/*.tsx (except the registry itself).
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.resolve(import.meta.dirname, "..", "src", "charts");
// Optional: --only=a,b,c limits the registry to those charts (used to preview while others are still being written).
const only = (process.argv.find((a) => a.startsWith("--only=")) ?? "").replace("--only=", "").split(",").filter(Boolean);
const ids = readdirSync(dir)
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .filter((id) => !only.length || only.includes(id))
  .sort();

const ident = (id) => "c_" + id.replace(/[^a-zA-Z0-9]/g, "_");
const body = [
  "// GENERATED by scripts/gen-registry.mjs. Do not edit by hand.",
  'import type { ChartModule } from "@/lib/types";',
  ...ids.map((id) => `import * as ${ident(id)} from "./${id}";`),
  "",
  `export const charts: ChartModule[] = [${ids.map(ident).join(", ")}];`,
  "",
].join("\n");
writeFileSync(path.join(dir, "registry.ts"), body);
console.log(`registry: ${ids.length} charts`);
